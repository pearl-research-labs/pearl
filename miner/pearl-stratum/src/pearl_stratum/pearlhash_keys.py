"""Recovered Pearlhash per-frame XOR keystreams.

Source: `C:/Source/pearl-investigation/wave16-domination/51_pearlhash_cipher_re.md` §2.3.

Each entry maps a frame index N (0-based; resets to 0 on each TCP reconnect)
to its 48-byte XOR keystream. The keystream cycles for the body length of the
frame: frame body = `XOR(plaintext, KEY_msg[N] * (body_len // 48 + 1))[:body_len]`.

Recovery method: known-plaintext attack against JSON-RPC templates harvested
from process memory dumps; verified bit-exact across multiple independent
captures (cap_long.pcap on production wallet + cap_verify.pcap on decoy wallet).
The keystreams are connection-independent — the wallet identity does NOT affect
the keystream.

What's KNOWN:
  KEY_MSG[0]    : login frame (`{"id":0,"method":"login",...}`)
  KEY_MSG[1..15]: report_info keepalives (`{"id":N,"method":"report_info",...}`)

What's UNKNOWN (recovery requires 1 paired capture each):
  KEY_MSG[16+]  : submit frames (`{"id":N,"method":"submit",...}`) — see
                  PEARLHASH_README.md §"How to capture a submit keystream".
  KEY_SRV_*     : server->client frames (login resp A/B/C, set_difficulty,
                  new_job, share_result) — completely unknown, see memo 51 §6.

KEY_DERIVATION is deterministic: the binary calls `srand(0)` at TCP connect and
emits `htonl(rand_N)` as the first 4 bytes of each C->S frame. The per-frame
48-byte XOR table itself is generated by an opaque algorithm inside the packed
pearl-miner v2 binary; static analysis hasn't recovered the function yet. Once
recovered (via Ghidra; memo 51 §4.2, ETA 3-5 days), this table would be
replaced by a generator. For now we ship the lookup table.
"""

