def _materialize() -> dict[int, bytes]:
    out = {}
    for idx, hexstr in KEY_MSG_HEX.items():
        kb = bytes.fromhex(hexstr)
        if len(kb) != 48:
            raise ValueError(
                f"KEY_MSG[{idx}] is {len(kb)} bytes, expected 48 (cipher invariant)"
            )
        out[idx] = kb
    return out


